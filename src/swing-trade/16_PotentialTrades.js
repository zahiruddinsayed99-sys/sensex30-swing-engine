/**
 * Tests Potential Trade creation using
 * the current RELIANCE.NS analysis.
 */
function runPotentialTradeTest() {
  try {
    const settings =
      getSettings();

    const validation =
      validateSettings(settings);

    if (!validation.valid) {
      SpreadsheetApp.getUi().alert(
        'Settings validation failed:\n\n' +
        validation.errors.join('\n')
      );
      return;
    }

    const symbol =
      'RELIANCE.NS';

    /*
     * Higher timeframe analysis
     */
    const higherTF =
      analyzeHigherTimeframe(
        symbol,
        settings
      );

    if (higherTF.status !== 'OK') {
      SpreadsheetApp.getUi().alert(
        'Higher TF analysis failed:\n\n' +
        higherTF.message
      );
      return;
    }

    /*
     * Lower timeframe analysis
     */
    const lowerTF =
      analyzeLowerTimeframe(
        symbol,
        settings
      );

    if (lowerTF.status !== 'OK') {
      SpreadsheetApp.getUi().alert(
        'Lower TF analysis failed:\n\n' +
        lowerTF.message
      );
      return;
    }

    /*
     * Lower timeframe market data
     * for volume divergence.
     */
    const marketData =
      getYahooData(
        symbol,
        settings['Lower Timeframe'],
        Number(
          settings['Candle Lookback']
        )
      );

    if (marketData.status !== 'OK') {
      SpreadsheetApp.getUi().alert(
        'Market data failed:\n\n' +
        marketData.message
      );
      return;
    }

    const volumeDivergence =
      analyzeVolumeDivergence(
        marketData.candles,
        Number(
          settings['Volume Lookback']
        )
      );

    if (
      volumeDivergence.status !== 'OK'
    ) {
      SpreadsheetApp.getUi().alert(
        'Volume divergence failed:\n\n' +
        volumeDivergence.message
      );
      return;
    }

    /*
     * Target
     */
    const targetAnalysis =
      calculateTarget(
        lowerTF.currentPrice,
        lowerTF.resistance,
        Number(
          settings['Minimum Target %']
        )
      );

    if (
      targetAnalysis.status !== 'OK'
    ) {
      SpreadsheetApp.getUi().alert(
        'Target calculation failed:\n\n' +
        targetAnalysis.message
      );
      return;
    }

    /*
     * Decision
     */
    const decision =
      evaluateDecision(
        higherTF,
        lowerTF,
        volumeDivergence,
        targetAnalysis
      );

    if (decision.status !== 'OK') {
      SpreadsheetApp.getUi().alert(
        'Decision Engine failed:\n\n' +
        decision.message
      );
      return;
    }

    /*
     * Potential Trade
     */
    const result =
      createPotentialTrade(
        symbol,
        settings,
        higherTF,
        lowerTF,
        volumeDivergence,
        targetAnalysis,
        decision
      );

    SpreadsheetApp.getUi().alert(
      'Potential Trade Test\n\n' +
      'Symbol: ' +
      symbol +
      '\n\n' +
      'Decision: ' +
      decision.finalDecision +
      '\n\n' +
      'Result: ' +
      result.status +
      '\n\n' +
      result.message +
      (
        result.tradeId
          ? '\n\nTrade ID: ' +
            result.tradeId
          : ''
      )
    );

  } catch (error) {
    SpreadsheetApp.getUi().alert(
      'Potential Trade test failed:\n\n' +
      error.message
    );
  }
}
